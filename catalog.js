export function pickKnowledge(entries, random=Math.random){
 const pool=[];
 for(const entry of entries){
  const list=variants[entry[0]]||[entry[1],`围绕${entry[0]}梳理核心概念，注意概念之间的联系。`,`结合教材和例题加深对${entry[0]}的理解。`];
  pool.push(...list);
 }
 for(let i=pool.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[pool[i],pool[j]]=[pool[j],pool[i]];}
 const count=pool.length>1&&(random()<.55)?2:1;
 return pool.slice(0,count).join('');
}
